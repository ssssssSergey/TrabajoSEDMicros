Disparo::Disparo(float x, float y, lv_obj_t* pantalla, bool enemigo) :
	pos(x, y), esEnemigo(enemigo)
{
    debeDestruirse = false;

    visual = lv_img_create(pantalla);
   	lv_img_set_src(visual, &disparo_pixel_art);

    //proteccion
    if (visual == nullptr) {
        debeDestruirse = true;
        return;
    }
    lv_obj_set_pos(visual, (int)pos.x, (int)pos.y);
}

Disparo::~Disparo() {
    if (visual != nullptr) {
        lv_obj_del(visual); //Limpia la pantalla automáticamente
    }
}

void Disparo::actualizar() {
    if (visual == nullptr) {
        debeDestruirse = true;
        return;
    }

    //velocidad del disparo depende de si es enemigo o del jugador
    if(esEnemigo){pos.y += 12;}
    else{ pos.y -= 12;}

    lv_obj_set_y(visual, (int)pos.y);
}


